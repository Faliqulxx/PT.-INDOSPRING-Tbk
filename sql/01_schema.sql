-- SQL Server (T-SQL). Soal 1: pembuatan tabel.
CREATE TABLE MSBARANG (
    KODE_BARANG VARCHAR(5)  NOT NULL PRIMARY KEY,
    NAMA_BARANG VARCHAR(50) NOT NULL,
    SATUAN      VARCHAR(5)  NOT NULL,
    KATEGORI    VARCHAR(10) NOT NULL
);

CREATE TABLE TRMUTASIHD (
    NO_TRANSAKSI    VARCHAR(5)  NOT NULL PRIMARY KEY,
    TANGGAL         DATE        NOT NULL,
    JENIS_TRANSAKSI VARCHAR(10) NOT NULL,   -- 'MASUK' / 'KELUAR'
    KATEGORI        VARCHAR(10) NOT NULL
);

CREATE TABLE TRMUTASIDT (
    NO_TRANSAKSI VARCHAR(5) NOT NULL,
    KODE_BARANG  VARCHAR(5) NOT NULL,
    QTY          INT        NOT NULL,
    PRIMARY KEY (NO_TRANSAKSI, KODE_BARANG),
    FOREIGN KEY (NO_TRANSAKSI) REFERENCES TRMUTASIHD (NO_TRANSAKSI),
    FOREIGN KEY (KODE_BARANG)  REFERENCES MSBARANG (KODE_BARANG)
);
